subroutine test_overlap_diat_exchange(error)

   !> Error handling
   type(error_type), allocatable, intent(out) :: error

   integer, parameter :: ng = 6
   integer, parameter :: nscale = 4
   real(wp), parameter :: kscale(3, nscale) = reshape([&
      & 0.7_wp, 1.3_wp, 0.4_wp, &
      & 0.9_wp, 0.9_wp, 0.9_wp, &
      & 1.0_wp, 1.0_wp, 1.0_wp, &
      & 1.0_wp, 1.0_wp, 0.4_wp], shape(kscale))

   type(cgto_type) :: cgtoj(3), cgtoi(3)
   type(diat_trafo_cache) :: cache_ji, cache_ij
   real(wp) :: vec(3), r2, sji(9, 9), dsji(9, 9, 3), sij(9, 9), dsij(9, 9, 3)
   real(wp) :: sji0(9, 9), dsji0(9, 9, 3), sij0(9, 9), dsij0(9, 9, 3)
   integer :: iscale, lj, li, nsj, nsi, ic, stat, ish, jsh, mapj, mapi, nj, ni
   real(wp), allocatable :: tmps(:, :), tmpds(:, :, :)

   ! Create two CGTOs with arbtrary shape at two centers
   call slater_to_gauss(ng, 1, 0, 1.2_wp, cgtoj(1), .true., stat)
   call slater_to_gauss(ng, 2, 1, 1.0_wp, cgtoj(2), .true., stat)
   call slater_to_gauss(ng, 3, 2, 1.5_wp, cgtoj(3), .true., stat)
   call slater_to_gauss(ng, 2, 0, 0.9_wp, cgtoi(1), .true., stat)
   call slater_to_gauss(ng, 3, 1, 1.4_wp, cgtoi(2), .true., stat)
   call slater_to_gauss(ng, 4, 2, 1.1_wp, cgtoi(3), .true., stat)

   ! Randomly oriented vector
   call random_number(vec)
   vec = vec - 0.5_wp
   r2 = sum(vec**2)

   ! Calculate overlap for the shell pair in both orientations
   sji0 = 0.0_wp
   dsji0 = 0.0_wp
   sij0 = 0.0_wp
   dsij0 = 0.0_wp
   do jsh = 1, size(cgtoj)
      mapj = smap(cgtoj(jsh)%ang)
      nj = msao(cgtoj(jsh)%ang)
      do ish = 1, size(cgtoi)
         mapi = smap(cgtoi(ish)%ang)
         ni = msao(cgtoi(ish)%ang)
         ! Forward orientation
         allocate(tmps(nj, ni), tmpds(3, nj, ni))
         call overlap_grad_cgto(cgtoj(jsh), cgtoi(ish), r2, vec, 100.0_wp, &
            & tmps, tmpds)
         sji0(mapj+1:mapj+nj, mapi+1:mapi+ni) = tmps
         do ic = 1, 3
            dsji0(mapj+1:mapj+nj, mapi+1:mapi+ni, ic) = tmpds(ic, :, :)
         end do
         deallocate(tmps, tmpds)
         ! Reversed orientation
         allocate(tmps(ni, nj), tmpds(3, ni, nj))
         call overlap_grad_cgto(cgtoi(ish), cgtoj(jsh), r2, -vec, 100.0_wp, &
            & tmps, tmpds)
         sij0(mapi+1:mapi+ni, mapj+1:mapj+nj) = tmps
         do ic = 1, 3
            dsij0(mapi+1:mapi+ni, mapj+1:mapj+nj, ic) = tmpds(ic, :, :)
         end do
         deallocate(tmps, tmpds)
      end do
   end do

   ! Check different scaling factors for both orientations
   do iscale = 1, nscale
      do lj = 0, 2
         do li = 0, 2
            nsj = sdim(lj)
            nsi = sdim(li)
            ! Scale forward orientation
            sji(:nsj, :nsi) = sji0(:nsj, :nsi)
            dsji(:nsj, :nsi, :) = dsji0(:nsj, :nsi, :)
            call setup_diat_trafo(cache_ji, vec, lj, li, grad=.true.)
            call diat_trafo(cache_ji, kscale(1, iscale), kscale(2, iscale), &
               & kscale(3, iscale), sji, dsji)
            ! Scale reversed orientation
            sij(:nsi, :nsj) = sij0(:nsi, :nsj)
            dsij(:nsi, :nsj, :) = dsij0(:nsi, :nsj, :)
            call setup_diat_trafo(cache_ij, -vec, li, lj, grad=.true.)
            call diat_trafo(cache_ij, kscale(1, iscale), kscale(2, iscale), &
               & kscale(3, iscale), sij, dsij)

            call check(error, maxval(abs(sji(:nsj, :nsi) &
               & - transpose(sij(:nsi, :nsj)))), 0.0_wp, thr=thr1)
            if (allocated(error)) return
            do ic = 1, 3
               call check(error, maxval(abs(dsji(:nsj, :nsi, ic) &
                  & + transpose(dsij(:nsi, :nsj, ic)))), 0.0_wp, thr=thr1)
               if (allocated(error)) return
            end do
         end do
      end do
   end do

